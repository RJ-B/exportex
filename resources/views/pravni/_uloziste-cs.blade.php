<h2>Co se ukládá v prohlížeči</h2>
<p>Web si do místního úložiště Vašeho prohlížeče ukládá tři drobnosti, aby si zapamatoval, jak si web nastavíte – a jen tehdy, když to sami zvolíte:</p>
<ul>
    <li><strong>exportex-lang-v2</strong> — zvolený jazyk (čeština nebo angličtina), až když ho přepnete.</li>
    <li><strong>exportex-theme-v2</strong> — zvolený světlý nebo tmavý režim, až když ho přepnete.</li>
    <li><strong>exportex-scroll</strong> — kam jste se na stránce dostali, aby Vás obnovení stránky vrátilo na stejné místo. Drží jen do zavření panelu (sessionStorage).</li>
</ul>
<p>Vše zůstává jen ve Vašem prohlížeči, nikam se neodesílá a nedá se z toho nic vyčíst o Vaší osobě. Smažete je vymazáním dat webu v prohlížeči.</p>

<h2>Externí obsah</h2>
<p>Web načítá veškerý obsah včetně písem z vlastní adresy. Nenavazuje spojení na cizí servery, takže se Vaše IP adresa nikam dál nepředává. Odkazy na WhatsApp a Telegram vedou ven, ale otevřou se až po Vašem kliknutí.</p>
